"""Split reference/assets/Mini_body.stl into a body mesh and four wheel meshes (Wavefront OBJ) for Godot.

STL frame: X = right, Y = up, Z = forward (hood at +Z), metres, wheels baked into the body.
Output frame (Godot): rotated 180 deg about Y so the car faces -Z; origin on the ground directly
below the CG, which model.m places car.c = 1.529 m ahead of the rear axle.
Wheel meshes are written relative to their own hub so they can spin and steer.
Usage: python3 -I tools/asset_pipeline/stl_to_obj.py <stl> <out_dir>
"""
import json
import struct
import sys

import numpy as np

CG_TO_REAR = 1.529          # model.m car.c
HUB_RADIUS_SELECT = 0.318   # slightly above R_w = 0.3043 to capture the tyre sidewall
HUBS_STL = {                # measured from the mesh (tyre contact-patch midpoints and ring fits)
    'rl': (+0.75, 0.31, -1.320), 'rr': (-0.75, 0.31, -1.320),
    'fl': (+0.75, 0.31, +1.163), 'fr': (-0.75, 0.31, +1.163),
}


def load_stl(path):
    data = open(path, 'rb').read()
    n = struct.unpack('<I', data[80:84])[0]
    rec = np.frombuffer(data[84:84 + 50 * n], dtype=np.dtype([('n', '<3f4'), ('v', '<9f4'), ('a', '<u2')]))
    return rec['v'].reshape(-1, 3, 3).astype(float)


def to_godot(p):
    # 180 deg about Y: (x, y, z) -> (-x, y, -z); then shift so the origin sits under the CG
    q = p * np.array([-1.0, 1.0, -1.0])
    rear_axle_z_godot = -HUBS_STL['rl'][2]
    cg_z = rear_axle_z_godot - CG_TO_REAR
    return q - np.array([0.0, 0.0, cg_z])


def write_obj(path, tris, name):
    normals = np.cross(tris[:, 1] - tris[:, 0], tris[:, 2] - tris[:, 0])
    lengths = np.linalg.norm(normals, axis=1, keepdims=True)
    normals = normals / np.where(lengths == 0, 1, lengths)
    with open(path, 'w') as f:
        f.write(f'# generated by tools/asset_pipeline/stl_to_obj.py from Mini_body.stl\no {name}\n')
        for t in tris:
            for p in t:
                f.write(f'v {p[0]:.5f} {p[1]:.5f} {p[2]:.5f}\n')
        for nrm in normals:
            f.write(f'vn {nrm[0]:.5f} {nrm[1]:.5f} {nrm[2]:.5f}\n')
        for i in range(len(tris)):
            a, b, c = 3 * i + 1, 3 * i + 2, 3 * i + 3
            f.write(f'f {a}//{i + 1} {b}//{i + 1} {c}//{i + 1}\n')


def main(stl_path, out_dir):
    tris = load_stl(stl_path)
    wheel_mask = np.zeros(len(tris), bool)
    meta = {'frame': 'Godot (Y up, car faces -Z), origin on ground below CG', 'wheels': {}}
    for key, hub in HUBS_STL.items():
        hub = np.array(hub)
        side = np.sign(hub[0])
        dz = tris[:, :, 2] - hub[2]
        dy = tris[:, :, 1] - hub[1]
        inside = (np.hypot(dz, dy) < HUB_RADIUS_SELECT) & (tris[:, :, 0] * side > 0.58)
        sel = inside.all(axis=1) & ~wheel_mask
        wheel_mask |= sel
        hub_g = to_godot(hub[None, :])[0]
        write_obj(f'{out_dir}/wheel_{key}.obj', to_godot(tris[sel].reshape(-1, 3)).reshape(-1, 3, 3) - hub_g, f'wheel_{key}')
        meta['wheels'][key] = {'hub': [round(float(c), 4) for c in hub_g], 'triangles': int(sel.sum())}
    body = to_godot(tris[~wheel_mask].reshape(-1, 3)).reshape(-1, 3, 3)
    write_obj(f'{out_dir}/body.obj', body, 'body')
    flat = body.reshape(-1, 3)
    meta['body'] = {'triangles': int((~wheel_mask).sum()),
                    'aabb_min': [round(float(c), 4) for c in flat.min(0)],
                    'aabb_max': [round(float(c), 4) for c in flat.max(0)]}
    json.dump(meta, open(f'{out_dir}/mini_r56_meta.json', 'w'), indent=2)
    print(json.dumps(meta, indent=2))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
